package com.itms.service.impl;

import com.itms.common.TrafficNetwork;
import com.itms.entity.TrafficData;

/** Shared ingestion contract for HTTP batches, Kafka and simulator fallback. */
final class TrafficValidation {
    private TrafficValidation() {}

    static void requireIntersection(String id) {
        if (id == null || !TrafficNetwork.INTERSECTIONS.containsKey(id))
            throw new IllegalArgumentException("Unknown intersection: " + id);
    }

    static void validateNewRecord(TrafficData data) {
        if (data == null) throw new IllegalArgumentException("traffic record is required");
        if (data.getId() != null) throw new IllegalArgumentException("id is generated by the server");
        requireIntersection(data.getIntersectionId());
        if (!TrafficNetwork.DIRECTIONS.contains(data.getDirection()))
            throw new IllegalArgumentException("direction must be NORTH, SOUTH, EAST or WEST");
        if (data.getVehicleCount() == null || data.getVehicleCount() < 0 || data.getVehicleCount() > 1000000)
            throw new IllegalArgumentException("vehicleCount must be between 0 and 1000000");
        requireRange(data.getAvgSpeed(), 0, 300, "avgSpeed", true);
        requireRange(data.getOccupancyRate(), 0, 100, "occupancyRate", false);
        requireRange(data.getLongitude(), -180, 180, "longitude", false);
        requireRange(data.getLatitude(), -90, 90, "latitude", false);
        if (data.getCongestionLevel() != null && (data.getCongestionLevel() < 0 || data.getCongestionLevel() > 3))
            throw new IllegalArgumentException("congestionLevel must be between 0 and 3");
        if (data.getDataSource() != null && data.getDataSource().length() > 20)
            throw new IllegalArgumentException("dataSource must contain at most 20 characters");
    }

    static void requireRange(Double value, double min, double max, String field, boolean required) {
        if (value == null && !required) return;
        if (value == null || !Double.isFinite(value) || value < min || value > max)
            throw new IllegalArgumentException(field + " must be finite and between " + min + " and " + max);
    }
}
